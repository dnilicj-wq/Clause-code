// Renders the hero scene's own stills: posters, designer views and swatches. BASE=http://localhost:5241 node tools/gen-assets.mjs [posters|views|swatches]
import { chromium } from 'playwright';
import sharp from 'sharp';
import fs from 'node:fs';
const BASE = process.env.BASE || 'http://localhost:5241', V = process.env.V || 'v1', PV = process.env.PV || 'sr1';
const what = process.argv[2] || 'all';
const keys = ['golden', 'silver', 'cream', 'autumn', 'flake', 'pearl', 'copper', 'highbuild'];
const b = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
async function shot(q, w, h, dpr = 1, clip) {
  const p = await b.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: dpr });
  p.on('console', (m) => { if (m.type() === 'error') console.log('console:', m.text()); });
  await p.goto(BASE + q);
  await p.waitForFunction(() => window.__ready === true, null, { timeout: 30000 }).catch(() => console.log('no __ready', q));
  const buf = await p.screenshot(clip ? { clip } : {});
  await p.close(); return buf;
}
fs.mkdirSync('public/posters', { recursive: true }); fs.mkdirSync('public/finish', { recursive: true });
if (what === 'all' || what === 'posters') {
  await sharp(await shot('/capture?k=poster', 1440, 900)).webp({ quality: 72 }).toFile(`public/posters/studio-d-${PV}.webp`);
  await sharp(await shot('/capture?k=poster', 390, 844, 2)).resize({ width: 640 }).webp({ quality: 68 }).toFile(`public/posters/studio-m-${PV}.webp`);
  console.log('posters');
}
if (what === 'all' || what === 'views') for (const k of keys) {
  const buf = await shot(`/capture?k=edge&f=${k}`, 1200, 900);
  await sharp(buf).webp({ quality: 74 }).toFile(`public/finish/${k}-view-1200-${V}.webp`);
  await sharp(buf).resize({ width: 640 }).webp({ quality: 70 }).toFile(`public/finish/${k}-view-640-${V}.webp`);
  console.log('view', k);
}
if (what === 'all' || what === 'swatches') {
  const inline = {};
  for (const k of keys) {
    const buf = await shot(`/capture?k=swatch&f=${k}`, 400, 400, 1, { x: 0, y: 0, width: 320, height: 320 });
    await sharp(buf).resize(160).webp({ quality: 78 }).toFile(`public/finish/${k}-160-${V}.webp`);
    inline[k] = 'data:image/webp;base64,' + (await sharp(buf).resize(96, 64, { fit: 'cover' }).webp({ quality: 60 }).toBuffer()).toString('base64');
    console.log('swatch', k);
  }
  fs.writeFileSync('config/swatches.ts', `// generated by tools/gen-assets.mjs swatches (stills of the hero's own surfaces, 96 px): inline so the hero card makes no extra requests\nexport const swatch: Record<string, string> = ${JSON.stringify(inline, null, 2)};\n`);
}
await b.close();
