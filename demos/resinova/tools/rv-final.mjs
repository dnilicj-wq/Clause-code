import { chromium } from 'playwright';
const [url, out] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
const errs = []; p.on('response', (r) => r.status() >= 400 && errs.push(r.status() + ' ' + r.url())); p.on('pageerror', (e) => errs.push(e.message));
await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForTimeout(4500);
await p.screenshot({ path: `${out}/f1-hero.png` });
await p.evaluate(() => scrollTo(0, document.querySelector('#services').offsetTop + 120)); await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/f2-services.png` });
await p.evaluate(() => document.querySelector('.card-venetian').scrollIntoView({ inline: 'start', block: 'center' })); await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/f2b-venetian-card.png` });
await p.locator('#design').scrollIntoViewIfNeeded(); await p.waitForTimeout(1200);
await p.getByRole('radio', { name: 'Ceiling' }).first().tap();
await p.getByRole('radio', { name: 'Venetian marble + gold leaf' }).first().tap();
const fins = await p.$$eval('#design [aria-label="Finish"] [role=radio]', (e) => e.map((x) => x.textContent));
await p.waitForTimeout(1300);
await p.evaluate(() => scrollTo(0, document.querySelector('#design').offsetTop + 470)); await p.waitForTimeout(700);
await p.screenshot({ path: `${out}/f3-configurator.png` });
await p.locator('#every-pour').scrollIntoViewIfNeeded(); await p.waitForTimeout(3500);
await p.screenshot({ path: `${out}/f4-marbling.png` });
const txt = await p.evaluate(() => document.body.innerText);
console.log(JSON.stringify({ fins, errs, wholeUK: /whole UK|across the UK/i.test(txt), free: /Free, from a photo/.test(txt), heading: txt.includes('Real pours, filmed on the job.') }));
await b.close();
