// Inline the hero card swatches (public/types/*-160-v3.webp, downsized to 96 px) into config/swatches.ts.
import sharp from 'sharp';
import fs from 'node:fs';
const keys = ['block', 'resin', 'tarmac', 'gravel', 'stone'];
let out = '// generated by scripts/inline-swatches.mjs from public/types/*-160-v3.webp: inline so the hero card makes no extra requests\nexport const swatch: Record<string, string> = {\n';
for (const k of keys) {
  const b = await sharp(`public/types/${k}-160-v3.webp`).resize(96, 64, { fit: 'cover' }).webp({ quality: 60 }).toBuffer();
  out += `  ${k}: 'data:image/webp;base64,${b.toString('base64')}',\n`;
}
fs.writeFileSync('config/swatches.ts', out + '};\n');
console.log('swatches', fs.statSync('config/swatches.ts').size);
