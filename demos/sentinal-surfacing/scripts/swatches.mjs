// Tiny inline swatches for the hero surface picker, cut from their own photos (inlined so the hero needs no extra requests).
import sharp from 'sharp'; import fs from 'node:fs';
const pick = { resin: ['public/client/darras-hall-640-v1.webp', 0.5, 0.82], micro: ['public/client/morpeth-floor-640-v1.webp', 0.55, 0.75], coat: ['public/client/int-grey-640-v1.webp', 0.5, 0.8] };
let out = '// Generated by scripts/swatches.mjs from their own photos (public/client). Do not edit by hand.\nexport const swatch: Record<string, string> = {\n';
for (const [k, [f, cx, cy]] of Object.entries(pick)) {
  const m = await sharp(f).metadata(); const w = Math.round(m.width * 0.34), h = Math.round(w * 0.5);
  const left = Math.max(0, Math.min(m.width - w, Math.round(m.width * cx - w / 2))), top = Math.max(0, Math.min(m.height - h, Math.round(m.height * cy - h / 2)));
  const b = await sharp(f).extract({ left, top, width: w, height: h }).resize(112, 56).webp({ quality: 62 }).toBuffer();
  out += `  ${k}: 'data:image/webp;base64,${b.toString('base64')}',\n`;
}
fs.writeFileSync('config/swatches.ts', out + '};\n');
